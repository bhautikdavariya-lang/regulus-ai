"""Stage 6 dataset: build it from the Stage 5 plan, then prove it is safe to train on.

    python scripts/prepare_stage6_dataset.py --plan artifacts/stage5_stage6/<run>/stage5/stage5_training_plan.json
    python scripts/prepare_stage6_dataset.py --plan <plan> --dry-run      # write the config, generate nothing

What it does, in order:

  1. reads stage5_training_plan.json and writes configs/training_v6.yaml from its
     recommended composition, so the category shares are traceable to measured
     failures rather than chosen by hand;
  2. generates the dataset from the read-only database (regulus.training.pipeline);
  3. validates it (regulus.training.validate), which re-verifies every
     "absent" identifier against the database;
  4. proves the separations the training gate requires and prints them:
       - no training question equals or nearly equals a benchmark question
       - no training example's split group is named by a benchmark question
       - no group appears in more than one split
  5. prints cardinalities by category and by split.

The database is opened read-only and only read. Nothing here trains anything.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

import yaml

from regulus.config import PROJECT_ROOT
from regulus.retrieval import Database
from regulus.training import load_training_config, prepare_dataset

DEFAULT_CONFIG = PROJECT_ROOT / "configs" / "training_v6.yaml"
BENCHMARKS = (
    "data/evaluation/datasets/baseline_v1.jsonl",
    "data/evaluation/datasets/retrieval_v1.jsonl",
    "data/evaluation/datasets/retrieval_v2.jsonl",
    "data/evaluation/datasets/stage5_v1.jsonl",
)
HEADER = """# Stage 6 training dataset (v6). Generated by scripts/prepare_stage6_dataset.py
# from {plan}; the category shares below are the Stage 5 plan's recommended
# composition, normalised. Do not hand-edit: regenerate from the plan instead.
#
#   python scripts/prepare_stage6_dataset.py --plan {plan}
#
# Two things differ from v1-v3 and both are opt-in flags, so those datasets
# still reproduce byte for byte:
#   * exclude_benchmark_groups: an example is dropped when its split group
#     (section or part) is named by ANY benchmark question, so no evaluation
#     section is trained on at all;
#   * the Stage 6 categories multi_provision / range_provision /
#     partial_provision, whose answers follow the Stage 4 generation contract.
"""


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--plan", required=True, help="stage5_training_plan.json from a completed Stage 5 run")
    p.add_argument("--config", default=str(DEFAULT_CONFIG), help="config file to write (default: configs/training_v6.yaml)")
    p.add_argument("--target", type=int, default=6000, help="target example count (default 6000)")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--workbook", default=None,
                   help="acceptance benchmark workbook used by the key gate")
    p.add_argument("--allow-unverified-key", action="store_true",
                   help="bypass the acceptance-key gate; for testing the generator only, never for "
                        "producing training data")
    p.add_argument("--dry-run", action="store_true", help="write the config and stop")
    p.add_argument("--skip-validation", action="store_true", help="generate without the database validation pass")
    return p.parse_args()


def write_config(plan_path: Path, config_path: Path, target: int, seed: int) -> dict:
    plan = json.loads(plan_path.read_text(encoding="utf-8"))
    shares = dict(plan.get("recommended_composition") or {})
    if not shares:
        raise SystemExit(f"{plan_path} has no recommended_composition")
    total = sum(shares.values())
    shares = {k: round(v / total, 4) for k, v in sorted(shares.items())}
    doc = {
        "dataset": {"version": "v6", "target_examples": target, "seed": seed, "train_ratio": 0.8,
                    "validation_ratio": 0.1, "test_ratio": 0.1, "output_dir": "data/training/datasets"},
        "sources": {"use_ecfr": True, "use_guidance": True, "retrievable_guidance_only": True},
        "quality": {"allow_unverified_sources": False, "min_paragraph_chars": 60, "max_paragraph_chars": 1500,
                    "max_context_chars": 3600, "near_duplicate_jaccard": 0.9, "benchmark_jaccard": 0.75,
                    "benchmark_jaccard_same_identifiers": 0.5, "max_paragraph_examples_per_section": 2,
                    "max_definition_examples_per_section": 12, "max_guidance_examples_per_document": 3,
                    "varied_refusal_openings": True, "guidance_context_negatives": True,
                    "exclude_benchmark_groups": True},
        "categories": shares,
        "benchmarks": list(BENCHMARKS),
    }
    config_path.write_text(HEADER.format(plan=plan_path.as_posix()) + "\n" + yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    return plan


def separation_report(paths: dict[str, Path], config) -> dict:
    """The three separations the training gate requires, checked on the written files."""
    from regulus.training.dedup import benchmark_groups, load_benchmark_questions
    from regulus.training.models import read_jsonl
    from regulus.training.text import normalise_question

    splits = {name: read_jsonl(paths[name]) for name in ("train", "validation", "test")}
    everything = [e for rows in splits.values() for e in rows]
    bench_questions = {normalise_question(q) for q in load_benchmark_questions(config.benchmarks)}
    bench_groups = benchmark_groups(config.benchmarks)

    question_overlap = sorted({e.id for e in everything if normalise_question(e.question) in bench_questions})
    group_overlap_bench = sorted({e.group for e in everything if e.group in bench_groups})
    groups_by_split = {name: {e.group for e in rows} for name, rows in splits.items()}
    cross_split = sorted(
        (groups_by_split["train"] & groups_by_split["validation"])
        | (groups_by_split["train"] & groups_by_split["test"])
        | (groups_by_split["validation"] & groups_by_split["test"])
    )
    return {
        "benchmark_questions_loaded": len(bench_questions),
        "benchmark_groups_excluded": len(bench_groups),
        "training_questions_equal_to_a_benchmark_question": question_overlap,
        "training_groups_named_by_a_benchmark": group_overlap_bench,
        "groups_in_more_than_one_split": cross_split,
        "clean": not question_overlap and not group_overlap_bench and not cross_split,
        "counts_by_split": {k: len(v) for k, v in splits.items()},
        "counts_by_category": {k: dict(sorted(Counter(e.category for e in v).items())) for k, v in splits.items()},
        "groups_by_split": {k: len(v) for k, v in groups_by_split.items()},
    }


def main() -> int:
    args = parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace", line_buffering=True)
    plan_path, config_path = Path(args.plan), Path(args.config)
    if not plan_path.is_file():
        print(f"PLAN NOT FOUND: {plan_path}", file=sys.stderr)
        return 2
    # Hard gate. The acceptance benchmark is a contractual test with an
    # unverified answer key; nothing may be trained until that key is locked by
    # an SME. This refuses on the execution path, not in a dashboard.
    if not args.allow_unverified_key:
        from regulus.evaluation.acceptance_benchmark import DEFAULT_WORKBOOK, load_acceptance_benchmark
        from regulus.evaluation.acceptance_gate import AcceptanceGateError, require_locked_key

        workbook = Path(args.workbook or DEFAULT_WORKBOOK)
        if workbook.is_file():
            try:
                require_locked_key(load_acceptance_benchmark(workbook).benchmark_key,
                                   "Stage 6 training-data preparation")
            except AcceptanceGateError as exc:
                print("BLOCKED", file=sys.stderr)
                print(exc, file=sys.stderr)
                return 3

    plan = write_config(plan_path, config_path, args.target, args.seed)
    print(f"Config written: {config_path}")
    print(f"  Stage 5 run: {plan.get('stage5_run')}  proceed={plan.get('proceed')}  ({plan.get('proceed_reason')})")
    if args.dry_run:
        return 0

    from regulus.training import validate_dataset
    from regulus.training.pipeline import dataset_paths

    config = load_training_config(config_path)
    db = Database.from_env()
    db.connect()
    try:
        print("Generating (database is read-only) ...", flush=True)
        result = prepare_dataset(config, db)
        manifest = result.manifest
        paths = dataset_paths(config)
        print(f"  dataset_sha256 ={manifest['dataset_sha256']}")
        for split, info in manifest["files"].items():
            print(f"  {split:<11} {info['examples']:>6} examples  {info['path']}")
        per_cat = manifest["generation"]["per_category"]
        print("\nCardinalities by category (candidates -> selected):")
        for cat, info in sorted(per_cat.items()):
            if info["candidates"] or info["selected"]:
                print(f"  {cat:<22} candidates {info['candidates']:>6}  after_dedup {info['after_dedup']:>6}"
                      f"  benchmark_excluded {info['benchmark_excluded']:>4}  group_excluded {info.get('benchmark_group_excluded', 0):>5}"
                      f"  target {info['target']:>5}  selected {info['selected']:>5}")
        sep = separation_report(paths, config)
        print("\nSeparation:")
        for key in ("benchmark_questions_loaded", "benchmark_groups_excluded", "training_questions_equal_to_a_benchmark_question",
                    "training_groups_named_by_a_benchmark", "groups_in_more_than_one_split", "counts_by_split", "groups_by_split"):
            print(f"  {key}: {sep[key]}")
        print(f"  CLEAN: {sep['clean']}")
        for split, counts in sep["counts_by_category"].items():
            print(f"  {split} by category: {counts}")
        out = Path(config.output_dir) / f"separation_{config.version}.json"
        out.write_text(json.dumps(sep, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"  written: {out}")

        if not args.skip_validation:
            print("\nValidating against the database ...", flush=True)
            report = validate_dataset(paths, config, db)
            for key in sorted(report.checks):
                print(f"  {key}: {report.checks[key]}")
            if report.errors:
                print(f"\nVALIDATION ERRORS ({len(report.errors)}):")
                for e in report.errors[:20]:
                    print(f"  - {e}")
                return 1
            print("  validation: OK")
        return 0 if sep["clean"] else 1
    finally:
        db.close()


if __name__ == "__main__":
    sys.exit(main())
